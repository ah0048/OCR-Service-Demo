-- Connect as BRK_COD in Toad and execute as a script (F5).
-- Stop workers before applying. Existing rows/data are preserved; DDL commits.
WHENEVER SQLERROR EXIT SQL.SQLCODE
SET SERVEROUTPUT ON

DECLARE
  column_count NUMBER;
BEGIN
  IF USER <> 'BRK_COD' THEN
    RAISE_APPLICATION_ERROR(-20001, 'Connect as BRK_COD before running this script');
  END IF;
  SELECT COUNT(*) INTO column_count FROM USER_TAB_COLUMNS
    WHERE TABLE_NAME = 'CLIENT_IMAGE_OCR_JOB' AND COLUMN_NAME = 'OCR_DETAILS_JSON';
  IF column_count = 0 THEN
    EXECUTE IMMEDIATE 'ALTER TABLE BRK_COD.CLIENT_IMAGE_OCR_JOB ADD (OCR_DETAILS_JSON CLOB)';
    DBMS_OUTPUT.PUT_LINE('Added OCR_DETAILS_JSON');
  ELSE
    DBMS_OUTPUT.PUT_LINE('Already exists: OCR_DETAILS_JSON');
  END IF;
END;
/

-- Verify DATA_TYPE is CLOB before restarting the worker.
SELECT COLUMN_NAME, DATA_TYPE FROM USER_TAB_COLUMNS
WHERE TABLE_NAME = 'CLIENT_IMAGE_OCR_JOB' AND COLUMN_NAME = 'OCR_DETAILS_JSON';
