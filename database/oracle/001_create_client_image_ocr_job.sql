-- Oracle 11g. Connect as BRK_COD in Toad and run as a script (F5).
-- New objects only: does not drop or change either existing production table.
-- DDL commits implicitly; this is a one-time installation, not a rerunnable migration.
WHENEVER SQLERROR EXIT SQL.SQLCODE

CREATE TABLE BRK_COD.CLIENT_IMAGE_OCR_JOB
(
  JOB_ID               NUMBER(19) NOT NULL,
  NIN_CODE             NUMBER(10) NOT NULL,
  STATUS               VARCHAR2(20 BYTE) DEFAULT 'PENDING' NOT NULL,

  -- Destination-compatible fields from CLIENTSOWNER.CLIENTS_OCR.
  -- NIN_CODE identifies the client; the extracted national ID is ID_NUMBER.
  CLIENT_NAME          VARCHAR2(100 BYTE),
  CLIENT_GENDER        VARCHAR2(1 BYTE), -- '1' = male, '2' = female
  ID_NUMBER            VARCHAR2(20 BYTE),
  DATE_OF_BIRTH        DATE,
  CLIENT_ADDRESS       NVARCHAR2(100),
  ID_EXPIRE_DATE       DATE,
  JOB_DESC             NVARCHAR2(400),
  HUSBAND_NAME         VARCHAR2(100 BYTE),
  MARITAL_STATUS       VARCHAR2(100 BYTE),
  RELIGION             VARCHAR2(100 BYTE),

  -- Preserve all original fields (including gender, marital status and religion).
  EXTRACTED_JSON       NCLOB,
  OCR_DETAILS_JSON     NCLOB,
  OCR_OUTCOME          VARCHAR2(30 BYTE),
  CONFIDENCE           NUMBER,
  ERROR_MESSAGE        VARCHAR2(1000 CHAR),

  -- Dates deliberately use Oracle DATE, as in CLIENTS_OCR. Use UTC by convention.
  INSERT_DATE          DATE DEFAULT CAST(SYS_EXTRACT_UTC(SYSTIMESTAMP) AS DATE) NOT NULL,
  STARTED_DATE         DATE,
  OCR_COMPLETED_DATE   DATE,

  CONSTRAINT PK_CLIENT_IMAGE_OCR_JOB PRIMARY KEY (JOB_ID),
  CONSTRAINT CK_CIOJ_STATUS CHECK (STATUS IN
    ('PENDING', 'UNDER_PROCESSING', 'OCR_SUCCESS', 'OCR_FAIL', 'FINISHED')),
  CONSTRAINT CK_CIOJ_CONFIDENCE CHECK (CONFIDENCE BETWEEN 0 AND 1),
  CONSTRAINT CK_CIOJ_GENDER CHECK (CLIENT_GENDER IN ('1', '2'))
);

CREATE SEQUENCE BRK_COD.CLIENT_IMAGE_OCR_JOB_SEQ
  START WITH 1 INCREMENT BY 1 MAXVALUE 9999999999999999999
  CACHE 20 NOCYCLE;

CREATE OR REPLACE TRIGGER BRK_COD.CLIENT_IMAGE_OCR_JOB_BI
BEFORE INSERT ON BRK_COD.CLIENT_IMAGE_OCR_JOB
FOR EACH ROW
BEGIN
  -- IDs are always generated here; callers omit JOB_ID.
  SELECT BRK_COD.CLIENT_IMAGE_OCR_JOB_SEQ.NEXTVAL
    INTO :NEW.JOB_ID FROM DUAL;
END;
/

CREATE INDEX BRK_COD.IX_CIOJ_PENDING
  ON BRK_COD.CLIENT_IMAGE_OCR_JOB (STATUS, INSERT_DATE, JOB_ID);

-- Verify the insert trigger before using the table.
SELECT OBJECT_NAME, STATUS FROM USER_OBJECTS
 WHERE OBJECT_NAME = 'CLIENT_IMAGE_OCR_JOB_BI';
SELECT NAME, LINE, POSITION, TEXT FROM USER_ERRORS
 WHERE NAME = 'CLIENT_IMAGE_OCR_JOB_BI'
 ORDER BY NAME, SEQUENCE;
